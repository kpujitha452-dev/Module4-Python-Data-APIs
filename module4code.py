import pandas as pd
import matplotlib.pyplot as plt

# 1. Create dataset
data = {
    "Name": ["Pujitha", "Anu", "Ravi", "Kiran", "Sita"],
    "Age": [19, 20, 19, 21, 20],
    "Marks": [85, 90, 75, 88, 95]
}
df = pd.DataFrame(data)

# 2. Clean data
df = df.drop_duplicates()
df["Marks"] = pd.to_numeric(df["Marks"], errors="coerce")
df = df.dropna(subset=["Marks"])

# 3. Analyze data
average = df["Marks"].mean()
highest = df["Marks"].max()
lowest = df["Marks"].min()
top_student = df.loc[df["Marks"].idxmax()]

print("STUDENT DATA")
print(df)
print("\nAverage Marks:", round(average, 2))
print("Highest Marks:", highest)
print("Lowest Marks:", lowest)
print("\nTop Student:")
print(top_student)

# 4. Create and save chart
plt.bar(df["Name"], df["Marks"])
plt.xlabel("Students")
plt.ylabel("Marks")
plt.title("Student Marks Analysis")
plt.tight_layout()
plt.savefig("student_marks.png")
plt.show()

# 5. Generate report
with open("analysis_report.txt", "w", encoding="utf-8") as file:
    file.write("STUDENT DATA ANALYSIS REPORT\n")
    file.write(f"Number of students: {len(df)}\n")
    file.write(f"Average marks: {average:.2f}\n")
    file.write(f"Highest marks: {highest}\n")
    file.write(f"Lowest marks: {lowest}\n")
    file.write(f"Top student: {top_student['Name']}\n")

print("\nReport saved as analysis_report.txt")
print("Chart saved as student_marks.png")